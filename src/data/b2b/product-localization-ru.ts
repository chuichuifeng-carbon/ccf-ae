export function translateProductTermRu(value: string): string {
  let text = value;
  for (const [ar, ru] of Object.entries(terms).sort((a, b) => b[0].length - a[0].length))
    text = text.replaceAll(ar, ru);
  if (/[\u0600-\u06ff]/.test(text)) throw new Error('Untranslated product term: ' + value);
  return text;
}

